"""Generate the platform migration from :mod:`cloud.intel.store.spec`.

    python -m cloud.intel.store.ddl            # print the SQL
    python -m cloud.intel.store.ddl --write    # (re)write cloud/db/migrations/0003_platform.sql

The migration is generated once and committed; ``test_platform_ddl`` fails if
the committed file drifts from the specs. Because applied migrations are
checksummed, a schema change after deployment is a *new* migration, never an
edit of this one.

Security model (PostgreSQL row-level security, same approach as 0001):

* ``careercloud.workspaces`` and ``careercloud.workspace_members`` hold tenancy.
* ``careercloud.member_role(ws)`` returns the caller's role in a workspace from
  ``auth.uid()``; it is ``security definer`` so policies can call it without
  recursing into the members table's own policy.
* Every platform table: members SELECT; writers (owner/admin/member) INSERT,
  UPDATE, DELETE; viewers read only. ``append_only`` tables grant no UPDATE or
  DELETE; ``system_write`` tables grant users SELECT only — the worker, which
  connects as the table owner, writes them.
* A trigger makes ``id``, ``workspace_id``, ``created_at`` and ``created_by``
  immutable for every role and bumps ``version``/``updated_at`` on each update.
"""

