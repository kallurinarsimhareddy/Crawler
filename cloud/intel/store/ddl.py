def _literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (dict, list)):
        import json

        if isinstance(value, list) and not value:
            return "'[]'::jsonb"
        return "'" + json.dumps(value, sort_keys=True).replace("'", "''") + "'::jsonb"
    return "'" + str(value).replace("'", "''") + "'"


def _choices_for(col: Col, version: str) -> Optional[tuple]:
    """The choices a column had as of ``version`` (a widened column keeps its original
    list in the migration that created it)."""
    if col.widened and version < col.widened[0]:
        return col.widened[1]
    return col.choices


def _column_sql(name: str, col: Col, spec: EntitySpec) -> str:
    pg = PG_TYPES[col.kind]
    parts = [f"{name:<22} {pg}"]
    if name == "id":
        parts = [f"{'id':<22} text primary key check (id ~ '^{spec.prefix}_[0-9a-f]{{32}}$')"]
        return " ".join(parts)
    if name == "workspace_id":
        return f"{'workspace_id':<22} uuid not null references careercloud.workspaces (id) on delete cascade"
    if col.required:
        parts.append("not null")
    if col.default is not None:
        if col.kind == "tags":
            parts.append("default '{}'::text[]")
        else:
            parts.append(f"default {_literal(col.default)}")
    elif name in ("created_at", "updated_at"):
        parts.append("default now()")
    checks: List[str] = []
    if col.max_len is not None and col.kind == "text":
        checks.append(f"char_length({name}) <= {col.max_len}")
    choices = _choices_for(col, spec.migration)
    if choices:
        options = ", ".join(_literal(c) for c in choices)
        checks.append(f"{name} in ({options})")
    if col.minimum is not None:
        checks.append(f"{name} >= {col.minimum:g}")
    if col.maximum is not None:
        checks.append(f"{name} <= {col.maximum:g}")
    if checks:
        parts.append("check (" + " and ".join(checks) + ")")
    return " ".join(parts)


def _later(col: Col, spec: EntitySpec) -> bool:
    """True when a later migration adds this column to the table."""
    return bool(col.added) and col.added > spec.migration


def added_sql(version: str) -> str:
    """``alter table ... add column`` for columns ``version`` adds to existing tables."""
    out: List[str] = []
    for spec in ENTITIES.values():
        for name, col in spec.columns.items():
            if col.added != version or spec.migration >= version:
                continue
            if col.required and col.default is None:
                raise ValueError(f"{spec.name}.{name}: an added required column needs a default")
            out.append(f"alter table careercloud.{spec.table} add column {_column_sql(name, col, spec).strip()};")
            if col.index:
                out.append(f"create index {spec.table}_by_ws_{name} on careercloud.{spec.table} (workspace_id, {name});")
    return "\n".join(out) + ("\n" if out else "")


def table_sql(spec: EntitySpec) -> str:
    t = f"careercloud.{spec.table}"
    columns = {**COMMON_COLUMNS, **{n: c for n, c in spec.columns.items() if not _later(c, spec)}}
    lines = [f"create table {t} ("]
    body = [f"  {_column_sql(name, col, spec)}" for name, col in columns.items()]
    lines.append(",\n".join(body))
    lines.append(");")
    out = ["-- " + (spec.description or spec.name), "\n".join(lines), ""]

    out.append(f"create index {spec.table}_by_ws_created on {t} (workspace_id, created_at desc, id desc);")
    for name, col in spec.columns.items():
        if col.index and not _later(col, spec):
            out.append(f"create index {spec.table}_by_ws_{name} on {t} (workspace_id, {name});")
    for group in spec.unique:
        cols = ", ".join(group)
        nullable = [c for c in group if not spec.columns[c].required]
        where = ""
        if nullable:
            where = " where " + " and ".join(f"{c} is not null" for c in nullable)
        out.append(f"create unique index {spec.table}_uq_{'_'.join(group)} on {t} (workspace_id, {cols}){where};")

    out.append(f"create trigger {spec.table}_guard before update on {t}")
    out.append("  for each row execute function careercloud.guard_platform_row();")
    out.append(f"alter table {t} enable row level security;")
    admin = bool(spec.admin_only) and spec.admin_only <= spec.migration
    policies, grants = _policies(spec, admin=admin)
    out.extend(policies)
    out.append(f"grant {', '.join(grants)} on {t} to authenticated;")
    return "\n".join(out) + "\n"


def _policies(spec: EntitySpec, *, admin: bool) -> Tuple[List[str], List[str]]:
    """RLS policies and grants for a table: members read and writers write, or only
    workspace admins (owner/admin) for an ``admin_only`` table."""
    t = f"careercloud.{spec.table}"
    read = "careercloud.can_admin(workspace_id)" if admin else "careercloud.is_member(workspace_id)"
    write = "careercloud.can_admin(workspace_id)" if admin else "careercloud.can_write(workspace_id)"
    out = [f"create policy {spec.table}_select on {t} for select to authenticated", f"  using ({read});"]
    grants = ["select"]
    if not spec.system_write:
        out.append(f"create policy {spec.table}_insert on {t} for insert to authenticated")
        out.append(f"  with check ({write} and created_by = auth.uid());")
        grants.append("insert")
        if not spec.append_only:
            out.append(f"create policy {spec.table}_update on {t} for update to authenticated")
            out.append(f"  using ({write}) with check ({write});")
            out.append(f"create policy {spec.table}_delete on {t} for delete to authenticated")
            out.append(f"  using ({write});")
            grants += ["update", "delete"]
    return out, grants


def restrict_sql(version: str) -> str:
    """Replace the policies of tables an earlier migration created that ``version`` makes admin-only."""
    out: List[str] = []
    for spec in ENTITIES.values():
        if spec.admin_only != version or spec.migration >= version:
            continue
        t = f"careercloud.{spec.table}"
        ops = ["select"]
        if not spec.system_write:
            ops += ["insert"] if spec.append_only else ["insert", "update", "delete"]
        out.append(f"-- {spec.table}: workspace admins only")
        out.extend(f"drop policy {spec.table}_{op} on {t};" for op in ops)
        out.extend(_policies(spec, admin=True)[0])
    return "\n".join(out) + ("\n" if out else "")


def widen_sql(version: str) -> str:
    """``alter table`` statements for columns whose choices ``version`` widens. PostgreSQL
    names an inline column check ``<table>_<column>_check``."""
    out: List[str] = []
    for spec in ENTITIES.values():
        for name, col in spec.columns.items():
            if not col.widened or col.widened[0] != version:
                continue
            if col.max_len is not None or col.minimum is not None or col.maximum is not None:
                raise ValueError(f"{spec.name}.{name}: only a plain choices check can be widened")
            options = ", ".join(_literal(c) for c in col.choices)
            constraint = f"{spec.table}_{name}_check"
            out.append(f"-- {spec.table}.{name}: widened choices")
            out.append(f"alter table careercloud.{spec.table} drop constraint {constraint},")
            out.append(f"  add constraint {constraint} check ({name} in ({options}));")
    return "\n".join(out) + ("\n" if out else "")


def generate(version: str = "0003") -> str:
    parts = [{"0003": _HEADER, "0004": _HEADER_0004, "0005": _HEADER_0005, "0006": _HEADER_0006,
              "0007": _HEADER_0007, "0008": _HEADER_0008, "0009": _HEADER_0009}[version]]
    widen = widen_sql(version)
    if widen:
        parts.append("\n-- ---------------------------------------------------------------------------\n")
        parts.append(widen)
    added = added_sql(version)
    if added:
        parts.append("\n-- ---------------------------------------------------------------------------\n")
        parts.append(added)
    restrict = restrict_sql(version)
    if restrict:
        parts.append("\n-- ---------------------------------------------------------------------------\n")
        parts.append(restrict)
    for spec in ENTITIES.values():
        if spec.migration != version:
            continue
        parts.append("\n-- ---------------------------------------------------------------------------\n")
        parts.append(table_sql(spec))
    if version == "0007":
        parts.append(_EXTRA_0007)
    parts.append(_FOOTER)
    return "".join(parts)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    for version, path in GENERATED.items():
        sql = generate(version)
        if args.write:
            path.write_text(sql, encoding="utf-8", newline="\n")
            count = sum(1 for spec in ENTITIES.values() if spec.migration == version)
            print(f"wrote {path} ({len(sql)} bytes, {count} tables)")
        else:
            sys.stdout.write(sql)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
